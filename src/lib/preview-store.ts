function opp(n: number, extra: PreviewRow): PreviewRow {
  const contato = contatos.find((c) => c.id === extra.contato_id) ?? contatos[0];
  return {
    id: id(n),
    titulo: extra.titulo,
    interesse: extra.interesse,
    nome_estabelecimento: contato.nome_estabelecimento,
    anos_operacao: contato.anos_operacao,
    descricao: extra.descricao ?? null,
    origem: extra.origem ?? "manual",
    etapa_id: extra.etapa_id,
    funil_id: extra.funil_id ?? funilId("comercial"),
    empresa_id: extra.empresa_id ?? (contato as { empresa_id?: string }).empresa_id ?? null,
    cargo_contato: extra.cargo_contato ?? (contato as { cargo?: string }).cargo ?? null,
    dor_cliente: extra.dor_cliente ?? null,
    impacto_negocio: extra.impacto_negocio ?? null,
    contato_id: contato.id,
    valor: extra.valor ?? null,
    data_visita: extra.data_visita ?? null,
    data_fechamento: extra.data_fechamento ?? null,
    motivo_perda: extra.motivo_perda ?? null,
    google_event_id: null,
    observacoes: extra.observacoes ?? null,
    responsavel: extra.responsavel ?? "Comercial",
    metadados: {},
    criado_em: extra.criado_em ?? iso(-4),
    atualizado_em: extra.atualizado_em ?? extra.criado_em ?? agora,
  };
}

